// 建立反向對照（繁→簡）
const T2S = {};
for (const s in S2T) if (!T2S[S2T[s]]) T2S[S2T[s]] = s;
const PHRASES_T2S = {};
for (const s in PHRASES_S2T) PHRASES_T2S[PHRASES_S2T[s]] = s;

export function convert(text, dir) {
  if (!text) return text;
  const phrases = dir === 's2t' ? PHRASES_S2T : PHRASES_T2S;
  const table = dir === 's2t' ? S2T : T2S;
  let out = text;
  for (const p in phrases) out = out.split(p).join(phrases[p]);
  out = [...out].map(ch => table[ch] || ch).join('');
  return out;
}
